    public function run(): void
    {
        $topic = Topic::where('code', 'ARB')->firstOrFail();

        $this->command->info("جاري استيراد أسئلة اللغة العربية للمحور: {$topic->name}");

        $questions = $this->getQuestions();

        $bar = $this->command->getOutput()->createProgressBar(count($questions));
        $bar->start();

        foreach ($questions as $qData) {
            $q = Question::create([
                'topic_id' => $topic->id,
                'type' => count($qData['options']) > 2 ? 'mcq' : 'true_false',
                'text' => $qData['text'],
                'difficulty' => 'medium',
                'is_active' => true,
            ]);

            foreach ($qData['options'] as $i => $opt) {
                QuestionOption::create([
                    'question_id' => $q->id,
                    'text' => $opt['text'],
                    'is_correct' => $opt['is_correct'],
                    'order' => $i + 1,
                ]);
            }

            $bar->advance();
        }

        $bar->finish();
        $this->command->newLine();
        $this->command->info("تم استيراد " . count($questions) . " سؤال بنجاح!");
    }

    private function getQuestions(): array
    {
        $raw = $this->getRawQuestions();
        $qs = [];

        foreach ($raw as $item) {
            $text = $item['text'];
            $opts = $item['options'] ?? ['صواب', 'خطأ'];

            // Skip entries that are just options with no valid question text
            if (empty($text) || strlen($text) < 3) continue;

            $options = [];
            foreach ($opts as $j => $o) {
                if (empty(trim($o))) continue;

                $isCorrect = false;
                // For True/False, صواب is correct
                if (count($opts) <= 2 && trim($o) === 'صواب') {
                    $isCorrect = true;
                }
                // For MCQ, first option is correct (user must verify)
                if ($j === 0 && count($opts) > 2) {
                    $isCorrect = true;
                }

                $options[] = [
                    'text' => trim($o),
                    'is_correct' => $isCorrect,
                ];
            }

            if (count($options) >= 2) {
                $qs[] = [
                    'text' => $text,
                    'options' => $options,
                ];
            }
        }

        return $qs;
    }

